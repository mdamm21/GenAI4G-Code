"""GRBL postprocessor — conservative GRBL-compatible G-code output.

GRBL v0 conventions:
- No % tape delimiters
- Comments with ( ... ) style
- G21/G20, G90, G54
- G0/G1, M3/M5
- End sequence: M5, G0 Zsafe, M2
- No tool changer commands (M06)
- No Fanuc-specific canned cycles
- No cutter compensation (G41/G42)
- safe_z missing → operations skipped with comment

Supported operations: drill, facing, slot, pocket, face_mill, laser.
"""

from __future__ import annotations

from cnc.postprocessors.common import (
    fmt,
    get_safe_z,
    get_units_code,
    get_work_coordinate_system,
    iter_operations,
)


def generate_gcode_from_operations(operation_plan: dict) -> str:
    """Convert a structured operation plan to conservative GRBL-compatible G-code.

    Operations with missing required parameters are skipped with a comment.
    """
    lines: list[str] = []
    units = operation_plan.get("units", "mm")
    machine_type = operation_plan.get("machine_type", "mill")
    _safe_z: float | None = get_safe_z(operation_plan)
    wcs = get_work_coordinate_system(operation_plan)
    assumptions = operation_plan.get("assumptions", [])
    warnings_plan = operation_plan.get("warnings", [])

    # --- Header (no % for GRBL) ---
    lines.append("(GENERATED BY GENAI4G-CODE — POSTPROCESSOR: GRBL)")
    lines.append("(CONSERVATIVE GRBL-STYLE OUTPUT)")
    lines.append("(REVIEW BEFORE RUNNING ON A MACHINE)")
    lines.append(f"(MACHINE TYPE: {machine_type.upper()})")
    lines.append(f"(UNITS: {units.upper()})")
    lines.append(f"(SAFE Z: {fmt(_safe_z) if _safe_z is not None else 'NOT SPECIFIED'})")
    lines.append(f"(WCS: {wcs})")
    for a in assumptions:
        lines.append(f"(ASSUMPTION: {a})")
    for w in warnings_plan:
        lines.append(f"(WARNING: {w})")

    # --- Safety setup ---
    unit_code = get_units_code(units)
    lines.append(f"{unit_code}")
    lines.append("G90")
    lines.append("G94")
    lines.append(f"{wcs}")

    if _safe_z is not None:
        lines.append(f"G0 Z{fmt(_safe_z)} (INITIAL RETRACT)")

    # --- Operations ---
    operations = iter_operations(operation_plan)
    if not operations:
        lines.append("(NO OPERATIONS DEFINED — SAFE SKELETON ONLY)")
    else:
        spindle_active = False
        current_spindle_speed: int | None = None

        for op in operations:
            if not isinstance(op, dict):
                lines.append(f"(SKIPPED NON-DICT OPERATION: {op!r})")
                continue

            op_name = op.get("name") or op.get("description") or "UNNAMED"
            op_type = op.get("type", "unknown")
            feedrate = op.get("feedrate_mmpm") or op.get("feedrate")
            spindle = op.get("spindle_rpm") or op.get("spindle_speed")
            params = op.get("parameters", {})

            lines.append("")
            lines.append(f"({op_name.upper()} — {op_type.upper()})")

            # Retract to safe Z before op
            if _safe_z is not None:
                lines.append(f"G0 Z{fmt(_safe_z)} (RETRACT TO SAFE Z)")
            else:
                lines.append("(WARNING: SAFE Z NOT DEFINED — RETRACT SKIPPED)")

            # Spindle management
            spindle_int = int(spindle) if spindle else None
            if spindle_int:
                if spindle_active and current_spindle_speed == spindle_int:
                    lines.append(f"(SPINDLE ALREADY RUNNING AT S{spindle_int})")
                else:
                    if spindle_active:
                        lines.append("M5 (SPINDLE STOP BEFORE SPEED CHANGE)")
                    lines.append(f"S{spindle_int} M3 (SPINDLE ON CW)")
                    current_spindle_speed = spindle_int
                    spindle_active = True
            else:
                lines.append("(WARNING: NO SPINDLE SPEED — M3 SKIPPED)")

            # Operation body
            if op_type in ("drill", "drilling", "peck_drill", "bore", "ream"):
                _append_drill(lines, op, feedrate, _safe_z)
            elif op_type in ("facing",):
                _append_facing(lines, op, feedrate, _safe_z)
            elif op_type in ("slot",):
                _append_slot(lines, op, feedrate, _safe_z)
            elif op_type in ("pocket", "pocket_mill"):
                _append_pocket(lines, op, feedrate, _safe_z)
            elif op_type in ("face_mill", "face"):
                _append_face_mill(lines, op, feedrate, op.get("depth_mm"), _safe_z)
            elif op_type in ("laser_cut", "laser_engrave", "laser_mark"):
                _append_laser(lines, op, feedrate, params)
            else:
                lines.append(f"(TODO: OPERATION TYPE '{op_type}' NOT YET IMPLEMENTED)")
                lines.append(f"(PARAMETERS: {params})")

            # Post-op retract
            if _safe_z is not None:
                lines.append(f"G0 Z{fmt(_safe_z)} (RETRACT AFTER OPERATION)")

        # Stop spindle after all operations
        if spindle_active:
            lines.append("M5 (SPINDLE STOP — END OF OPERATIONS)")

    # --- Program end (GRBL style: M5, G0 Zsafe, M2) ---
    lines.append("")
    lines.append("M5 (SPINDLE OFF)")
    if _safe_z is not None:
        lines.append(f"G0 Z{fmt(_safe_z)} (RETRACT TO SAFE Z)")
    lines.append("M2 (PROGRAM END)")

    return "\n".join(lines)


